"""Generate pwa/data.js from the server's seed data (single source of truth).

Run:  .venv/bin/python -m tools.make_static_data

Produces pwa/data.js — the sourced catalog, aliases, goal registry, and
regulatory status labels as a static JS object for the installable PWA.
No user data is ever included: only the synthetic, sourced catalog.
"""

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from peptide_safety.goals import GOALS_EXPLANATION, TRACKING_GOALS
from peptide_safety.seed import CATALOG_ALIASES, CATALOG_ROWS
from peptide_safety.__init__ import ALLOWED_UNITS, REGULATORY_STATUSES


def goal_to_static(g):
    """Serialize one goal: label, optional fields, optional note."""
    out = {"label": g["label"]}
    fields = []
    if "field" in g:
        fields.append(g["field"])
    fields.extend(g.get("fields", []))
    if fields:
        out["fields"] = fields
    if g.get("note"):
        out["note"] = g["note"]
    return out


def main():
    catalog = [
        {
            "name": r[0],
            "category": r[1],
            "regulatory_status": r[2],
            "evidence_note": r[3],
            "source_url": r[4],
            "review_status": r[5],
            "source_type": r[6],
        }
        for r in CATALOG_ROWS
    ]
    goals = {k: goal_to_static(v) for k, v in TRACKING_GOALS.items()}
    payload = {
        "CATALOG": catalog,
        "ALIASES": dict(CATALOG_ALIASES),
        "GOALS": goals,
        "GOALS_EXPLANATION": GOALS_EXPLANATION,
        "STATUSES": REGULATORY_STATUSES,
        "UNITS": list(ALLOWED_UNITS),
    }
    out_path = REPO / "pwa" / "data.js"
    out_path.write_text(
        "// GENERATED by tools/make_static_data.py from peptide_safety seed"
        " data — do not edit by hand.\n"
        "// Sourced synthetic catalog + goal registry only; contains NO user"
        " data.\n"
        "const STATIC_DATA = " + json.dumps(payload, indent=2) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {out_path} ({len(catalog)} catalog entries, "
          f"{len(goals)} goals)")


if __name__ == "__main__":
    main()
